 await page.locator('[data-scope="navigation"]').click()
 await page.locator('#q').fill('Open')
 await page.locator('#lib .it').first().click()
 await page.getByRole('tab',{name:'Moshpit',exact:true}).click()
 assert.equal(await page.locator('#ct').evaluate(el=>el.classList.contains('arming')),false)
 // Native details provide keyboard disclosure; search includes closed categories.
 await page.locator('[data-scope="system"]').click()
 await page.locator('#q').fill('')
