 assert.equal(await page.locator('#lib .it').getAttribute('aria-disabled'),'true')
 await page.locator('#lib .it').click({force:true})
 assert.equal(await page.locator('#applybtn').isVisible(),false,'incompatible gesture cannot bind')
 await page.locator('#q').fill('Keyboard shortcut')
 await page.locator('#lib .it').click()
 await page.locator('#fv').fill('ctrl+x')
 const beforePending=await page.evaluate(()=>JSON.stringify(MOCK_PROFILES.moshpit))
 await page.locator('#fv').press('Control+Shift+K')
 assert.equal(await page.evaluate(()=>JSON.stringify(MOCK_PROFILES.moshpit)),beforePending,'parameter recording must not edit the previous action')
 await page.locator('[data-k="b0"]').click()
 assert.equal(await page.locator('#applybtn').isVisible(),false)
 // Editing an inactive app must not change the live app status.
 assert.match(await page.locator('#chip-td').innerText(),/Moshpit/)
 await page.getByRole('tab',{name:'TouchDesigner',exact:true}).click()
 assert.match(await page.locator('#chip-td').innerText(),/Moshpit/)
