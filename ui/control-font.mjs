const TRACK=1.7
export const displayText=value=>Array.from(String(value??'').toUpperCase().replaceAll('—','-').replaceAll('–','-').replaceAll('…','..')).map(c=>Object.hasOwn(FONT,c)?c:'-').join('')
export function textWidth(value,cap=11){const s=displayText(value);return s?([...s].reduce((n,c)=>n+FONT[c][0]+TRACK,0)-TRACK)*cap/6:0}
export function fitLabel(value,{cap=11,maxWidth=76}={}){
 const s=displayText(value).trim();if(textWidth(s,cap)<=maxWidth)return[s]
 const words=s.split(' ')
 for(let i=1;i<words.length;i++){const a=words.slice(0,i).join(' '),b=words.slice(i).join(' ');if(textWidth(a,cap)<=maxWidth&&textWidth(b,cap)<=maxWidth)return[a,b]}
 let t=s;while(t&&textWidth(t+'..',cap)>maxWidth)t=t.slice(0,-1)
 return[t.trimEnd()+'..']
}
export function textLines(value,x,y,cap=11){
 const s=displayText(value),scale=cap/6,lines=[];let left=x-textWidth(s,cap)/2
 for(const c of s){const[w,...parts]=FONT[c];for(const p of parts)lines.push(p.map(([u,v])=>[left+u*scale,y-cap/2+v*scale]));left+=(w+TRACK)*scale}
 return lines
}

